CREATE OR REPLACE PROCEDURE sp_register_user (
    p_full_name IN users.full_name%TYPE,
    p_email IN users.email%TYPE,
    p_password IN users.password_hash%TYPE,
    p_role IN users.role%TYPE DEFAULT 'user',
    p_user_id OUT users.user_id%TYPE
) AS
BEGIN
    INSERT INTO users (full_name, email, password_hash, role)
    VALUES (TRIM(p_full_name), LOWER(TRIM(p_email)), p_password, p_role)
    RETURNING user_id INTO p_user_id;
    COMMIT;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'Email or user ID already exists.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END sp_register_user;
/
SHOW ERRORS;

CREATE OR REPLACE PROCEDURE sp_toggle_favorite (
    p_user_id IN favorites.user_id%TYPE,
    p_room_id IN favorites.room_id%TYPE,
    p_status OUT VARCHAR2
) AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM favorites
    WHERE user_id = p_user_id AND room_id = p_room_id;
    IF v_count > 0 THEN
        DELETE FROM favorites WHERE user_id = p_user_id AND room_id = p_room_id;
        p_status := 'REMOVED';
    ELSE
        INSERT INTO favorites (user_id, room_id) VALUES (p_user_id, p_room_id);
        p_status := 'ADDED';
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END sp_toggle_favorite;
/
SHOW ERRORS;

