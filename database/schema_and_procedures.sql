CREATE TABLE users (
    user_id NUMBER PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    phone VARCHAR2(20),
    role VARCHAR2(20) DEFAULT 'user' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('user', 'owner', 'admin'))
);
CREATE TABLE rooms (
    room_id NUMBER PRIMARY KEY,
    title VARCHAR2(150) NOT NULL,
    location VARCHAR2(100) NOT NULL,
    city VARCHAR2(50) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    room_type VARCHAR2(30) NOT NULL,
    gender_pref VARCHAR2(20) DEFAULT 'any' NOT NULL,
    description VARCHAR2(1000),
    amenities VARCHAR2(500),
    image_url VARCHAR2(300),
    owner_id NUMBER NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_room_owner FOREIGN KEY (owner_id) REFERENCES users(user_id),
    CONSTRAINT chk_room_price CHECK (price > 0),
    CONSTRAINT chk_room_type CHECK (room_type IN ('Single', 'Double Sharing', 'Triple Sharing')),
    CONSTRAINT chk_gender_pref CHECK (gender_pref IN ('any', 'male', 'female'))
);
CREATE TABLE favorites (
    favorite_id NUMBER PRIMARY KEY,
    user_id NUMBER NOT NULL,
    room_id NUMBER NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_favorite_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_favorite_room FOREIGN KEY (room_id) REFERENCES rooms(room_id) ON DELETE CASCADE,
    CONSTRAINT unique_user_room UNIQUE (user_id, room_id)
);
CREATE TABLE contact_messages (
    contact_id NUMBER PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    subject VARCHAR2(150),
    message VARCHAR2(1000) NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL
);
CREATE SEQUENCE seq_user_id START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE seq_room_id START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE seq_favorite_id START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE seq_contact_id START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER trg_users_bi
BEFORE INSERT ON users FOR EACH ROW
BEGIN
    IF :NEW.user_id IS NULL THEN
        SELECT seq_user_id.NEXTVAL INTO :NEW.user_id FROM DUAL;
    END IF;
END;
